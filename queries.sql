-- Query 16: Customer lifetime value analysis
-- Purpose: Calculate total value of each customer
SELECT 
    c.customer_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    c.email,
    c.registration_date,
    COUNT(r.rental_id) AS total_rentals,
    SUM(r.total_amount) AS lifetime_value,
    AVG(r.total_amount) AS avg_transaction,
    MAX(r.rental_date) AS last_rental_date
FROM Customers c
LEFT JOIN Rentals r ON c.customer_id = r.customer_id
GROUP BY c.customer_id, c.first_name, c.last_name, c.email, c.registration_date
ORDER BY lifetime_value DESC NULLS LAST;

-- Query 17: Vehicle utilization rate
-- Purpose: Calculate how often each vehicle is rented
WITH VehicleStats AS (
    SELECT 
        v.vehicle_id,
        v.make,
        v.model,
        v.license_plate,
        v.purchase_date,
        COUNT(r.rental_id) AS rental_count,
        SUM(r.expected_return_date - r.rental_date) AS total_rental_days,
        CURRENT_DATE - v.purchase_date AS days_in_fleet
    FROM Vehicles v
    LEFT JOIN Rentals r ON v.vehicle_id = r.vehicle_id
    WHERE v.purchase_date IS NOT NULL
    GROUP BY v.vehicle_id, v.make, v.model, v.license_plate, v.purchase_date
)
SELECT 
    vehicle_id,
    make || ' ' || model AS vehicle,
    license_plate,
    rental_count,
    total_rental_days,
    days_in_fleet,
    ROUND((total_rental_days::DECIMAL / days_in_fleet) * 100, 2) AS utilization_percentage
FROM VehicleStats
WHERE days_in_fleet > 0
ORDER BY utilization_percentage DESC;

-- Query 18: Payment method analysis
-- Purpose: Analyze payment preferences
SELECT 
    p.payment_method,
    COUNT(p.payment_id) AS transaction_count,
    SUM(p.amount) AS total_amount,
    AVG(p.amount) AS avg_transaction,
    ROUND((COUNT(p.payment_id)::DECIMAL / (SELECT COUNT(*) FROM Payments)) * 100, 2) AS percentage_of_transactions
FROM Payments p
WHERE p.status = 'completed'
GROUP BY p.payment_method
ORDER BY total_amount DESC;

-- Query 19: Find available vehicles for a specific date range
-- Purpose: Check vehicle availability for booking
SELECT 
    v.vehicle_id,
    v.make || ' ' || v.model AS vehicle,
    vt.type_name,
    v.license_plate,
    v.daily_rate,
    v.mileage
FROM Vehicles v
JOIN VehicleTypes vt ON v.type_id = vt.type_id
WHERE v.status = 'available'
  AND v.vehicle_id NOT IN (
      SELECT vehicle_id
      FROM Rentals
      WHERE status = 'active'
        AND (
            (rental_date <= '2024-12-30' AND expected_return_date >= '2024-12-25')
        )
  )
ORDER BY v.daily_rate;

-- Query 20: Complete rental history with payment information
-- Purpose: Full audit trail of rentals and payments
SELECT 
    r.rental_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    c.email,
    v.make || ' ' || v.model AS vehicle,
    v.license_plate,
    r.rental_date,
    r.return_date,
    r.expected_return_date,
    r.total_amount AS rental_amount,
    r.status AS rental_status,
    p.payment_id,
    p.amount AS payment_amount,
    p.payment_method,
    p.payment_date,
    p.status AS payment_status
FROM Rentals r
JOIN Customers c ON r.customer_id = c.customer_id
JOIN Vehicles v ON r.vehicle_id = v.vehicle_id
LEFT JOIN Payments p ON r.rental_id = p.rental_id
ORDER BY r.rental_date DESC, r.rental_id;

-- ============================================================================
-- DATA INTEGRITY AND MAINTENANCE QUERIES
-- ============================================================================

-- Query 21: Check for data inconsistencies
-- Purpose: Find rentals with mismatched payment amounts
SELECT 
    r.rental_id,
    r.total_amount AS rental_amount,
    SUM(p.amount) AS total_payments,
    r.total_amount - COALESCE(SUM(p.amount), 0) AS difference
FROM Rentals r
LEFT JOIN Payments p ON r.rental_id = p.rental_id AND p.status = 'completed'
WHERE r.status = 'completed'
GROUP BY r.rental_id, r.total_amount
HAVING r.total_amount != COALESCE(SUM(p.amount), 0)
ORDER BY difference DESC;

-- Query 22: Database statistics summary
-- Purpose: Overall system statistics
SELECT 
    (SELECT COUNT(*) FROM Customers) AS total_customers,
    (SELECT COUNT(*) FROM Vehicles) AS total_vehicles,
    (SELECT COUNT(*) FROM Vehicles WHERE status = 'available') AS available_vehicles,
    (SELECT COUNT(*) FROM Rentals WHERE status = 'active') AS active_rentals,
    (SELECT COUNT(*) FROM Rentals WHERE status = 'completed') AS completed_rentals,
    (SELECT COALESCE(SUM(total_amount), 0) FROM Rentals WHERE status = 'completed') AS total_revenue,
    (SELECT COUNT(*) FROM Payments WHERE status = 'completed') AS total_payments;
