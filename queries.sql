-- Query 11: Find the most popular vehicle (most rented)
-- Purpose: Identify which vehicle has been rented the most times
WITH VehicleRentalCounts AS (
    SELECT 
        v.vehicle_id,
        v.make,
        v.model,
        v.year,
        v.license_plate,
        COUNT(r.rental_id) AS rental_count
    FROM Vehicles v
    LEFT JOIN Rentals r ON v.vehicle_id = r.vehicle_id
    GROUP BY v.vehicle_id, v.make, v.model, v.year, v.license_plate
)
SELECT 
    vehicle_id,
    make || ' ' || model || ' (' || year || ')' AS vehicle,
    license_plate,
    rental_count
FROM VehicleRentalCounts
WHERE rental_count = (SELECT MAX(rental_count) FROM VehicleRentalCounts);

-- Query 12: Calculate monthly revenue trend
-- Purpose: Show revenue by month for trend analysis
SELECT 
    TO_CHAR(r.rental_date, 'YYYY-MM') AS month,
    COUNT(r.rental_id) AS total_rentals,
    SUM(r.total_amount) AS total_revenue,
    AVG(r.total_amount) AS avg_rental_value
FROM Rentals r
WHERE r.status = 'completed'
GROUP BY TO_CHAR(r.rental_date, 'YYYY-MM')
ORDER BY month DESC;

-- Query 13: Find customers who haven't rented in the last 30 days
-- Purpose: Identify inactive customers for marketing campaigns
SELECT 
    c.customer_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    c.email,
    MAX(r.rental_date) AS last_rental_date,
    CURRENT_DATE - MAX(r.rental_date) AS days_since_last_rental
FROM Customers c
JOIN Rentals r ON c.customer_id = r.customer_id
GROUP BY c.customer_id, c.first_name, c.last_name, c.email
HAVING MAX(r.rental_date) < CURRENT_DATE - INTERVAL '30 days'
ORDER BY days_since_last_rental DESC;

-- Query 14: Rank vehicles by revenue within each type
-- Purpose: Identify top performers in each vehicle category
SELECT 
    vt.type_name,
    v.make || ' ' || v.model AS vehicle,
    v.license_plate,
    COALESCE(SUM(r.total_amount), 0) AS total_revenue,
    RANK() OVER (PARTITION BY vt.type_name ORDER BY COALESCE(SUM(r.total_amount), 0) DESC) AS rank_in_type
FROM VehicleTypes vt
JOIN Vehicles v ON vt.type_id = v.type_id
LEFT JOIN Rentals r ON v.vehicle_id = r.vehicle_id AND r.status = 'completed'
GROUP BY vt.type_name, v.vehicle_id, v.make, v.model, v.license_plate
ORDER BY vt.type_name, rank_in_type;

-- Query 15: Find vehicles with overdue rentals
-- Purpose: Identify rentals that are past their expected return date
SELECT 
    r.rental_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    c.phone,
    v.make || ' ' || v.model AS vehicle,
    v.license_plate,
    r.rental_date,
    r.expected_return_date,
    CURRENT_DATE - r.expected_return_date AS days_overdue,
    r.total_amount
FROM Rentals r
JOIN Customers c ON r.customer_id = c.customer_id
JOIN Vehicles v ON r.vehicle_id = v.vehicle_id
WHERE r.status = 'active' 
  AND r.expected_return_date < CURRENT_DATE
ORDER BY days_overdue DESC;

