-- Query 1: Retrieve all available vehicles
-- Purpose: List all vehicles that are currently available for rent
SELECT 
    v.vehicle_id,
    v.make,
    v.model,
    v.year,
    v.license_plate,
    v.color,
    vt.type_name,
    v.daily_rate,
    v.mileage
FROM Vehicles v
JOIN VehicleTypes vt ON v.type_id = vt.type_id
WHERE v.status = 'available'
ORDER BY v.daily_rate;

