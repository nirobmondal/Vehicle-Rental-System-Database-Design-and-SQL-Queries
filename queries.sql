-- Purpose: Update the mileage of a vehicle after it's returned
UPDATE Vehicles
SET mileage = mileage + 500,
    last_service_date = CURRENT_DATE
WHERE vehicle_id = 1;

-- Query 5: Delete a cancelled rental
-- Purpose: Remove a rental that was cancelled
DELETE FROM Rentals
WHERE rental_id = 6 AND status = 'cancelled';

-- ============================================================================
-- INTERMEDIATE QUERIES (JOINs and Aggregations)
-- ============================================================================

-- Query 6: List all active rentals with customer and vehicle details
-- Purpose: Show currently active rentals with full information
SELECT 
    r.rental_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    c.email,
    c.phone,
    v.make || ' ' || v.model AS vehicle,
    v.license_plate,
    r.rental_date,
    r.expected_return_date,
    r.total_amount,
    CURRENT_DATE - r.rental_date AS days_rented
FROM Rentals r
JOIN Customers c ON r.customer_id = c.customer_id
JOIN Vehicles v ON r.vehicle_id = v.vehicle_id
WHERE r.status = 'active'
ORDER BY r.rental_date DESC;

-- Query 7: Calculate total revenue by vehicle type
-- Purpose: Show revenue generated by each vehicle type
SELECT 
    vt.type_name,
    COUNT(r.rental_id) AS total_rentals,
    SUM(r.total_amount) AS total_revenue,
    AVG(r.total_amount) AS avg_rental_amount
FROM VehicleTypes vt
LEFT JOIN Vehicles v ON vt.type_id = v.type_id
LEFT JOIN Rentals r ON v.vehicle_id = r.vehicle_id AND r.status = 'completed'
GROUP BY vt.type_name
ORDER BY total_revenue DESC NULLS LAST;

-- Query 8: Find customers with multiple rentals
-- Purpose: Identify repeat customers
SELECT 
    c.customer_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    c.email,
    COUNT(r.rental_id) AS rental_count,
    SUM(r.total_amount) AS total_spent
FROM Customers c
JOIN Rentals r ON c.customer_id = r.customer_id
GROUP BY c.customer_id, c.first_name, c.last_name, c.email
HAVING COUNT(r.rental_id) > 1
ORDER BY rental_count DESC;

-- Query 9: Calculate average rental duration by vehicle type
-- Purpose: Analyze rental patterns by vehicle type
SELECT 
    vt.type_name,
    COUNT(r.rental_id) AS rental_count,
    AVG(r.expected_return_date - r.rental_date) AS avg_rental_days,
    MIN(r.expected_return_date - r.rental_date) AS min_rental_days,
    MAX(r.expected_return_date - r.rental_date) AS max_rental_days
FROM VehicleTypes vt
JOIN Vehicles v ON vt.type_id = v.type_id
JOIN Rentals r ON v.vehicle_id = r.vehicle_id
WHERE r.status IN ('completed', 'active')
GROUP BY vt.type_name
ORDER BY avg_rental_days DESC;

-- Query 10: List vehicles that need maintenance (high mileage)
-- Purpose: Identify vehicles with mileage over 20,000 miles
SELECT 
    v.vehicle_id,
    v.make,
    v.model,
    v.year,
    v.license_plate,
    v.mileage,
    v.last_service_date,
    CURRENT_DATE - v.last_service_date AS days_since_service
FROM Vehicles v
WHERE v.mileage > 20000
   OR (v.last_service_date IS NOT NULL AND CURRENT_DATE - v.last_service_date > 90)
ORDER BY v.mileage DESC;

